/**
 * Validate that code compiled against the {@code javax.persistence} based Hibernate 5 keeps working with the
 * {@code jakarta.persistence} classes bridged by the patched Hibernate, against a real database.
 * <p>
 * The Hibernate objects are cast (instead of assigned) to their {@code javax.persistence} type since the Java compiler
 * does not see the {@code javax.persistence} super types (they only exist at the JVM level). The generated bytecode
 * then calls the same methods as code compiled against Hibernate 5.
 *
 * @version $Id$
 */
class JavaxPersistenceBridgeTest
{
    private static final MethodHandles.Lookup LOOKUP = MethodHandles.publicLookup();

    private static final String ENTITY = LegacyEntity.class.getName();

    @RegisterExtension
    private static LogCaptureExtension logCapture = new LogCaptureExtension(LogLevel.WARN);

    private static SessionFactory sessionFactory;

    @BeforeAll
    static void beforeAll()
    {
        sessionFactory = TestSessionFactories.create("javax", logCapture);
    }

    @AfterAll
    static void afterAll()
    {
        sessionFactory.close();
    }

    @BeforeEach
    void beforeEach()
    {
        inTransaction(session -> {
            session.createMutationQuery("delete from " + ENTITY).executeUpdate();
            session.persist(new LegacyEntity(1, "one"));
            session.persist(new LegacyEntity(2, "two"));
            session.persist(new LegacyEntity(3, "three"));
            session.persist(new LegacyEntity(4, "ten"));
        });
    }

    private void inTransaction(Consumer<Session> consumer)
    {
        try (Session session = sessionFactory.openSession()) {
            Transaction transaction = session.beginTransaction();
            consumer.accept(session);
            transaction.commit();
        }
    }

    private static List<Long> ids(List<LegacyEntity> entities)
    {
        return entities.stream().map(LegacyEntity::getId).toList();
    }

    /**
     * Signatures of Hibernate 5 methods using {@code javax.persistence} types (as found in code compiled against
     * Hibernate 5).
     */
    static Object[][] hibernate5Methods()
    {
        return new Object[][] {
            {Session.class, "find", MethodType.methodType(Object.class, Class.class, Object.class, LockModeType.class)},
            {Session.class, "getFlushMode", MethodType.methodType(FlushModeType.class)},
            {Session.class, "setFlushMode", MethodType.methodType(void.class, FlushModeType.class)},
            {Session.class, "getCriteriaBuilder", MethodType.methodType(CriteriaBuilder.class)},
            {Session.class, "createQuery", MethodType.methodType(Query.class, CriteriaQuery.class)},
            {Session.class, "getTransaction", MethodType.methodType(Transaction.class)},
            {SessionFactory.class, "createEntityManager", MethodType.methodType(EntityManager.class)},
            {Query.class, "setFlushMode", MethodType.methodType(Query.class, FlushModeType.class)},
            {Query.class, "setLockMode", MethodType.methodType(Query.class, LockModeType.class)},
            {Query.class, "getLockMode", MethodType.methodType(LockModeType.class)},
            {Transaction.class, "commit", MethodType.methodType(void.class)}};
    }

    @ParameterizedTest
    @MethodSource("hibernate5Methods")
    void hibernate5MethodIsLinkable(Class<?> owner, String name, MethodType type) throws Exception
    {
        // Resolve the method the same way the JVM resolves a call compiled against Hibernate 5
        assertNotNull(LOOKUP.findVirtual(owner, name, type));
    }

    @Test
    void javaxSuperTypes()
    {
        assertTrue(EntityManager.class.isAssignableFrom(Session.class));
        assertTrue(EntityManagerFactory.class.isAssignableFrom(SessionFactory.class));
        assertTrue(TypedQuery.class.isAssignableFrom(Query.class));
        assertTrue(EntityTransaction.class.isAssignableFrom(Transaction.class));
        assertTrue(PersistenceException.class.isAssignableFrom(HibernateException.class));

        // The javax.persistence super types are only visible to the JVM
        assertFalse(List.of(Session.class.getGenericInterfaces()).contains(EntityManager.class));
    }

    @Test
    void entityManager()
    {
        EntityManagerFactory factory = EntityManagerFactory.class.cast(sessionFactory);

        EntityManager entityManager = factory.createEntityManager();
        try {
            EntityTransaction transaction = entityManager.getTransaction();
            transaction.begin();
            entityManager.persist(new LegacyEntity(5, "five"));
            transaction.commit();
            assertFalse(transaction.isActive());

            entityManager.clear();

            assertEquals(FlushModeType.AUTO, entityManager.getFlushMode());
            entityManager.setFlushMode(FlushModeType.COMMIT);
            assertEquals(FlushModeType.COMMIT, entityManager.getFlushMode());

            assertEquals("five", entityManager.find(LegacyEntity.class, 5L, LockModeType.NONE).getName());
        } finally {
            entityManager.close();
        }
    }

    @Test
    void typedQuery()
    {
        try (Session session = sessionFactory.openSession()) {
            EntityManager entityManager = EntityManager.class.cast(session);

            TypedQuery<LegacyEntity> query =
                entityManager.createQuery("from " + ENTITY + " where name like :name order by id", LegacyEntity.class);
            assertEquals("name", query.getParameter("name").getName());

            query.setParameter("name", "t%").setFlushMode(FlushModeType.COMMIT).setMaxResults(2);

            assertEquals(FlushModeType.COMMIT, query.getFlushMode());
            assertEquals(List.of(2L, 3L), ids(query.getResultList()));
        }
    }

    @Test
    void criteria()
    {
        try (Session session = sessionFactory.openSession()) {
            EntityManager entityManager = EntityManager.class.cast(session);

            CriteriaBuilder builder = entityManager.getCriteriaBuilder();
            CriteriaQuery<LegacyEntity> criteria = builder.createQuery(LegacyEntity.class);
            Root<LegacyEntity> root = criteria.from(LegacyEntity.class);
            // Pass arrays of javax.persistence types
            criteria.select(root)
                .where(new Predicate[] {builder.like(root.<String>get("name"), "t%"), builder.notEqual(root.get("id"), 3L)})
                .orderBy(builder.desc(root.get("id")));

            assertEquals(List.of(4L, 2L), ids(entityManager.createQuery(criteria).getResultList()));
        }
    }

    @Test
    void hibernate5CriteriaQuery() throws Throwable
    {
        try (Session session = sessionFactory.openSession()) {
            // Same calls as code compiled against org.hibernate.Session from Hibernate 5
            MethodHandle getCriteriaBuilder =
                LOOKUP.findVirtual(Session.class, "getCriteriaBuilder", MethodType.methodType(CriteriaBuilder.class));
            MethodHandle createQuery = LOOKUP.findVirtual(Session.class, "createQuery",
                MethodType.methodType(Query.class, CriteriaQuery.class));

            CriteriaBuilder builder = (CriteriaBuilder) getCriteriaBuilder.invoke(session);
            CriteriaQuery<LegacyEntity> criteria = builder.createQuery(LegacyEntity.class);
            Root<LegacyEntity> root = criteria.from(LegacyEntity.class);
            criteria.select(root).where(builder.equal(root.get("name"), "two"));

            Query<?> query = (Query<?>) createQuery.invoke(session, criteria);

            assertEquals(List.of(2L), ids(query.list().stream().map(LegacyEntity.class::cast).toList()));
        }
    }

    @Test
    void catchJavaxPersistenceException()
    {
        try (Session session = sessionFactory.openSession()) {
            PersistenceException exception =
                assertThrows(PersistenceException.class, () -> session.get("UnknownEntity", 1L));

            assertInstanceOf(HibernateException.class, exception);
        }
    }

    /**
     * A class inheriting the same default bridge method from two unrelated interfaces fails with an
     * {@link IncompatibleClassChangeError} when the method is called, so the patcher must generate it in the class (or
     * a common sub interface).
     */
    @Test
    void noAmbiguousBridgeMethod() throws IOException, URISyntaxException
    {
        Path classes = Path.of(Session.class.getProtectionDomain().getCodeSource().getLocation().toURI());

        List<String> ambiguous = new ArrayList<>();
        int checked = 0;
        try (Stream<Path> stream = Files.walk(classes)) {
            for (Path file : (Iterable<Path>) stream::iterator) {
                String path = classes.relativize(file).toString();
                if (path.endsWith(".class") && (path.startsWith("org/hibernate/") || path.startsWith("jakarta/"))) {
                    Class<?> type = load(path.substring(0, path.length() - 6).replace('/', '.'));
                    if (type != null && !type.isInterface() && !Modifier.isAbstract(type.getModifiers())) {
                        ambiguous.addAll(getAmbiguousBridgeMethods(type));
                        ++checked;
                    }
                }
            }
        }

        assertTrue(checked > 1000, "Only " + checked + " classes checked");
        assertEquals(List.of(), ambiguous);
    }

    private static Class<?> load(String name)
    {
        try {
            Class<?> type = Class.forName(name, false, JavaxPersistenceBridgeTest.class.getClassLoader());
            // Make sure the methods can be resolved
            type.getMethods();

            return type;
        } catch (LinkageError | ClassNotFoundException e) {
            // Optional dependency missing
            return null;
        }
    }

    private static List<String> getAmbiguousBridgeMethods(Class<?> type)
    {
        // The default methods using javax.persistence types provided by the interfaces of the class
        Map<String, Set<Method>> defaults = new HashMap<>();
        for (Class<?> interfaceType : getAllInterfaces(type)) {
            for (Method method : interfaceType.getDeclaredMethods()) {
                if (method.isDefault() && usesJavaxPersistence(method)) {
                    defaults.computeIfAbsent(key(method), k -> new LinkedHashSet<>()).add(method);
                }
            }
        }

        List<String> ambiguous = new ArrayList<>();
        for (Map.Entry<String, Set<Method>> entry : defaults.entrySet()) {
            if (!isImplementedByClass(type, entry.getKey())) {
                Set<Method> methods = entry.getValue();
                // Keep only the maximally specific ones
                List<Method> maximal = methods.stream().filter(m -> methods.stream().noneMatch(
                    o -> o != m && m.getDeclaringClass().isAssignableFrom(o.getDeclaringClass()))).toList();
                if (maximal.size() > 1) {
                    ambiguous.add(type.getName() + '#' + entry.getKey() + ' '
                        + maximal.stream().map(m -> m.getDeclaringClass().getName()).toList());
                }
            }
        }

        return ambiguous;
    }

    private static Set<Class<?>> getAllInterfaces(Class<?> type)
    {
        Set<Class<?>> result = new LinkedHashSet<>();
        for (Class<?> current = type; current != null; current = current.getSuperclass()) {
            addInterfaces(current, result);
        }

        return result;
    }

    private static void addInterfaces(Class<?> type, Set<Class<?>> result)
    {
        for (Class<?> interfaceType : type.getInterfaces()) {
            if (result.add(interfaceType)) {
                addInterfaces(interfaceType, result);
            }
        }
    }

    private static boolean isImplementedByClass(Class<?> type, String key)
    {
        for (Class<?> current = type; current != null; current = current.getSuperclass()) {
            for (Method method : current.getDeclaredMethods()) {
                if (!Modifier.isAbstract(method.getModifiers()) && key(method).equals(key)) {
                    return true;
                }
            }
        }

        return false;
    }

    private static boolean usesJavaxPersistence(Method method)
    {
        return MethodType.methodType(method.getReturnType(), method.getParameterTypes()).toMethodDescriptorString()
            .contains("Ljavax/persistence/");
    }

    private static String key(Method method)
    {
        return method.getName()
            + MethodType.methodType(method.getReturnType(), method.getParameterTypes()).toMethodDescriptorString();
    }
}
