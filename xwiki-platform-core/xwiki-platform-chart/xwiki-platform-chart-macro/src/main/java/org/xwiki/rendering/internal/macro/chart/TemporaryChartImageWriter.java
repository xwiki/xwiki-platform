package org.xwiki.rendering.internal.macro.chart;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.GeneralSecurityException;
import java.security.SecureRandom;
import java.util.HexFormat;

import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;
import javax.inject.Inject;
import javax.inject.Named;
import javax.inject.Singleton;

import org.xwiki.component.annotation.Component;
import org.xwiki.model.reference.DocumentReference;
import org.xwiki.rendering.macro.MacroExecutionException;
import org.xwiki.resource.ResourceReference;
import org.xwiki.resource.ResourceReferenceSerializer;
import org.xwiki.resource.SerializeResourceReferenceException;
import org.xwiki.resource.UnsupportedResourceReferenceException;
import org.xwiki.resource.temporary.TemporaryResourceReference;
import org.xwiki.resource.temporary.TemporaryResourceStore;
import org.xwiki.url.ExtendedURL;

/**
 * Save generated Chart images to the temporary resource store. Each image is owned by the document holding the charted
 * data, so only users who can view that document can access the image. Identical images of the same document are
 * stored only once.
 *
 * @version $Id$
 * @since 4.2M3
 */
@Component
@Named("tmp")
@Singleton
public class TemporaryChartImageWriter implements ChartImageWriter
{
    /**
     * The module name used when creating temporary resources.
     */
    private static final String MODULE_NAME = "chart";

    private static final String HMAC_ALGORITHM = "HmacSHA256";

    private static final int KEY_LENGTH = 32;

    /**
     * The key used to compute the image ids. The ids are derived from the image content so that identical images share
     * the same file, but with a secret key so that they can't be computed outside of this component. A new key for each
     * run is fine since the temporary files don't outlive it.
     */
    private final SecretKeySpec idKey;

    /**
     * Used to store the generated chart image.
     */
    @Inject
    private TemporaryResourceStore temporaryResourceStore;

    /**
     * Used to compute the URL to the temporary stored image generated by the chart.
     */
    @Inject
    private ResourceReferenceSerializer<ResourceReference, ExtendedURL> resourceReferenceSerializer;

    /**
     * Creates a new writer, with a new random key for computing the image ids.
     * @since 18.10.0RC1
     * @since 18.4.8
     * @since 17.10.15
     * @since 16.10.20
     */
    public TemporaryChartImageWriter()
    {
        byte[] key = new byte[KEY_LENGTH];
        new SecureRandom().nextBytes(key);
        this.idKey = new SecretKeySpec(key, HMAC_ALGORITHM);
    }

    @Override
    public ImageId writeImage(byte[] imageData, DocumentReference dataDocumentReference)
        throws MacroExecutionException
    {
        ImageId imageId = new ImageId(computeId(imageData), dataDocumentReference);

        try {
            File imageFile = this.temporaryResourceStore.getTemporaryFile(getTemporaryResourceReference(imageId));
            if (!imageFile.exists()) {
                // Write to a temporary file first and then move it in place, so that the image file is never read
                // while it's partially written (e.g. when an identical image is being generated concurrently).
                Path directory = Files.createDirectories(imageFile.getParentFile().toPath());
                Path partialFile = Files.createTempFile(directory, imageFile.getName(), ".part");
                try {
                    Files.write(partialFile, imageData);
                    Files.move(partialFile, imageFile.toPath(), StandardCopyOption.ATOMIC_MOVE,
                        StandardCopyOption.REPLACE_EXISTING);
                } finally {
                    Files.deleteIfExists(partialFile);
                }
            }
        } catch (IOException e) {
            throw new MacroExecutionException("Failed to write the generated chart image", e);
        }

        return imageId;
    }

    @Override
    public String getURL(ImageId imageId) throws MacroExecutionException
    {
        try {
            return this.resourceReferenceSerializer.serialize(getTemporaryResourceReference(imageId)).serialize();
        } catch (SerializeResourceReferenceException | UnsupportedResourceReferenceException e) {
            throw new MacroExecutionException("Failed to compute the URL of the generated chart image", e);
        }
    }

    private String computeId(byte[] imageData) throws MacroExecutionException
    {
        try {
            Mac mac = Mac.getInstance(HMAC_ALGORITHM);
            mac.init(this.idKey);
            return HexFormat.of().formatHex(mac.doFinal(imageData));
        } catch (GeneralSecurityException e) {
            throw new MacroExecutionException("Failed to compute the id of the generated chart image", e);
        }
    }

    private TemporaryResourceReference getTemporaryResourceReference(ImageId imageId)
    {
        return new TemporaryResourceReference(MODULE_NAME, String.format("%s.png", imageId.getId()),
            imageId.getDataDocumentReference());
    }
}
