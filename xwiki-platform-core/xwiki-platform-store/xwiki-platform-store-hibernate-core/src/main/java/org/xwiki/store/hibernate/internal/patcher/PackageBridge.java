package org.xwiki.store.hibernate.internal.patcher;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.Iterator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;

import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.Type;
import org.objectweb.asm.tree.AbstractInsnNode;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.MethodInsnNode;
import org.objectweb.asm.tree.MethodNode;

/**
 * Make the classes of a package (the target, for example {@code jakarta.persistence}) usable by code compiled against
 * another package with the same API (the source, for example {@code javax.persistence}).
 * <ul>
 * <li>Each target interface having a twin in the source package also extends it, but only at the JVM level: the twin
 * is not added to the generic signature, which is what the Java compiler uses to resolve the super types, so that code
 * compiled against the target package does not see (or need) the source package. Converting a target interface to its
 * source twin is thus just a cast. Enums and arrays are converted with {@code PackageBridgeUtils}.</li>
 * <li>A target exception class whose super class comes from {@code java.lang} (the root of the exception hierarchy)
 * extends its source twin instead (again only at the JVM level), so that catching the source exception also catches
 * the target one.</li>
 * <li>A synthetic bridge method using the source types is generated for each public method using target types in the
 * public target types and in the public types of the bridged packages (for example {@code org/hibernate/}, except the
 * {@code internal} packages): it converts the arguments to the target types, calls the target method and converts
 * back the result. The bridge methods are marked as synthetic bridges, like the ones generated by the Java compiler:
 * it does not call them, but still reads them when checking overrides, so the source package must be in the compile
 * classpath of code extending the bridged types.</li>
 * <li>Since a class implementing two unrelated interfaces providing the same default bridge method would fail with an
 * {@link IncompatibleClassChangeError} when it's called, the bridge method is also generated in the sub types
 * inheriting conflicting bridge methods.</li>
 * </ul>
 *
 * @version $Id$
 */
final class PackageBridge
{
    private static final String UTILS = "org/xwiki/store/hibernate/internal/bridge/PackageBridgeUtils";

    private static final String CONSTRUCTOR = "<init>";

    private static final Set<String> ROOT_EXCEPTIONS =
        Set.of("java/lang/RuntimeException", "java/lang/Exception", "java/lang/Error");

    private static final Set<String> OBJECT_METHODS =
        Set.of("equals(Ljava/lang/Object;)Z", "hashCode()I", "toString()Ljava/lang/String;");

    private record Bridge(String name, String sourceDescriptor, String targetDescriptor, boolean isStatic)
    {
        String key()
        {
            return this.name + this.sourceDescriptor;
        }
    }

    /**
     * What to change in a class.
     */
    private static final class ClassPlan
    {
        private String addedInterface;

        private String superName;

        private final Map<String, Bridge> bridges = new LinkedHashMap<>();

        /**
         * The inherited abstract methods to redeclare.
         */
        private final List<MethodNode> redeclared = new ArrayList<>();
    }

    /**
     * The bridge methods visible from a type.
     */
    private static final class Inherited
    {
        /**
         * The bridge methods inherited from the super classes or declared in the class.
         */
        private final Set<String> concrete = new HashSet<>();

        /**
         * The maximally specific interfaces providing each default bridge method.
         */
        private final Map<String, Set<String>> defaults = new HashMap<>();
    }

    private final String targetPrefix;

    private final String sourcePrefix;

    private final List<String> bridgedPrefixes;

    private final Map<String, ClassNode> sourceClasses;

    private final Map<String, ClassNode> classes = new HashMap<>();

    private final Map<String, ClassPlan> plans = new HashMap<>();

    private final Map<String, Inherited> inherited = new HashMap<>();

    private final Map<String, Set<String>> superTypes = new HashMap<>();

    private final Set<String> twinInterfaces = new HashSet<>();

    private final Set<String> twinEnums = new HashSet<>();

    private final Set<String> twinExceptions = new HashSet<>();

    private final List<String> errors = new ArrayList<>();

    private int bridgeCount;

    /**
     * @param targetPrefix the prefix of the target internal names (for example {@code jakarta/persistence/})
     * @param sourcePrefix the prefix of the source internal names (for example {@code javax/persistence/})
     * @param sourceJar the JAR containing the source classes
     * @param bridgedPrefixes the prefixes of the other packages in which to generate bridge methods
     * @throws IOException when failing to read the JAR
     */
    PackageBridge(String targetPrefix, String sourcePrefix, Path sourceJar, List<String> bridgedPrefixes)
        throws IOException
    {
        this.targetPrefix = targetPrefix;
        this.sourcePrefix = sourcePrefix;
        this.bridgedPrefixes = bridgedPrefixes;
        this.sourceClasses = new HashMap<>();
        load(sourceJar, this.sourceClasses);
    }

    private static void load(Path jarPath, Map<String, ClassNode> classes) throws IOException
    {
        try (JarFile jar = new JarFile(jarPath.toFile())) {
            for (Iterator<JarEntry> it = jar.entries().asIterator(); it.hasNext();) {
                JarEntry entry = it.next();
                if (entry.getName().endsWith(".class") && !entry.getName().endsWith("module-info.class")
                    && !entry.getName().startsWith("META-INF/")) {
                    try (InputStream stream = jar.getInputStream(entry)) {
                        ClassNode node = new ClassNode();
                        new ClassReader(stream.readAllBytes()).accept(node, ClassReader.SKIP_CODE);
                        classes.putIfAbsent(node.name, node);
                    }
                }
            }
        }
    }

    /**
     * Decide what to change in the classes of the passed JARs.
     *
     * @param jars all the JARs whose classes are copied
     * @throws IOException when failing to read the JARs
     */
    void plan(List<Path> jars) throws IOException
    {
        for (Path jar : jars) {
            load(jar, this.classes);
        }

        // The target types which can be converted to their source twin
        for (ClassNode node : this.classes.values()) {
            ClassNode twin = node.name.startsWith(this.targetPrefix) ? this.sourceClasses.get(toSource(node.name))
                : null;
            if (twin == null || (node.access & Opcodes.ACC_PUBLIC) == 0 || (twin.access & Opcodes.ACC_PUBLIC) == 0) {
                continue;
            }
            if ((node.access & Opcodes.ACC_ANNOTATION) != 0) {
                // Annotations cannot have super interfaces
                continue;
            }
            if ((node.access & Opcodes.ACC_ENUM) != 0) {
                this.twinEnums.add(node.name);
            } else if ((node.access & Opcodes.ACC_INTERFACE) != 0) {
                this.twinInterfaces.add(node.name);
                plan(node.name).addedInterface = twin.name;
            } else if (ROOT_EXCEPTIONS.contains(node.superName) && node.superName.equals(twin.superName)) {
                this.twinExceptions.add(node.name);
                plan(node.name).superName = twin.name;
            }
        }

        // The bridge methods
        for (ClassNode node : this.classes.values()) {
            if (isBridged(node)) {
                for (MethodNode method : node.methods) {
                    planBridge(node, method);
                }
            }
        }

        // Make sure the source twins are fully implemented
        for (String name : this.twinInterfaces) {
            validate(this.classes.get(name), this.sourceClasses.get(toSource(name)));
        }

        // Resolve the conflicts between default bridge methods
        for (String name : this.classes.keySet()) {
            getInherited(name);
        }
    }

    private ClassPlan plan(String name)
    {
        return this.plans.computeIfAbsent(name, k -> new ClassPlan());
    }

    private boolean isBridged(ClassNode node)
    {
        // Enums are converted (and their values() method must stay unique)
        if ((node.access & Opcodes.ACC_PUBLIC) == 0
            || (node.access & (Opcodes.ACC_ANNOTATION | Opcodes.ACC_ENUM)) != 0) {
            return false;
        }

        if (node.name.startsWith(this.targetPrefix)) {
            // Including the target types without source twin since they can be super types of target types with a
            // source twin
            return true;
        }

        if (node.name.contains("/internal/")) {
            return false;
        }

        return this.bridgedPrefixes.stream().anyMatch(node.name::startsWith);
    }

    private void planBridge(ClassNode node, MethodNode method)
    {
        if ((method.access & Opcodes.ACC_PUBLIC) == 0
            || (method.access & (Opcodes.ACC_SYNTHETIC | Opcodes.ACC_BRIDGE)) != 0 || method.name.startsWith("<")
            || !isConvertible(method.desc)) {
            return;
        }

        Bridge bridge = new Bridge(method.name, toSourceDescriptor(method.desc), method.desc,
            (method.access & Opcodes.ACC_STATIC) != 0);
        plan(node.name).bridges.put(bridge.key(), bridge);
    }

    /**
     * @return true if the descriptor contains at least one target type and all of them can be converted
     */
    private boolean isConvertible(String descriptor)
    {
        List<Type> types = new ArrayList<>(List.of(Type.getArgumentTypes(descriptor)));
        types.add(Type.getReturnType(descriptor));

        boolean found = false;
        for (Type type : types) {
            Type element = type.getSort() == Type.ARRAY ? type.getElementType() : type;
            if (element.getSort() == Type.OBJECT && element.getInternalName().startsWith(this.targetPrefix)) {
                String name = element.getInternalName();
                if (type.getSort() == Type.ARRAY && type.getDimensions() > 1 || !this.twinInterfaces.contains(name)
                    && !this.twinEnums.contains(name) && !this.twinExceptions.contains(name)) {
                    return false;
                }
                found = true;
            }
        }

        return found;
    }

    private void validate(ClassNode target, ClassNode source)
    {
        for (MethodNode method : source.methods) {
            if ((method.access & (Opcodes.ACC_STATIC | Opcodes.ACC_PRIVATE | Opcodes.ACC_SYNTHETIC)) != 0) {
                continue;
            }

            String targetDescriptor = toTargetDescriptor(method.desc);
            boolean found = targetDescriptor.equals(method.desc) ? hasMethod(target.name, method.name, method.desc)
                : hasBridge(target.name, method.name + method.desc);
            if (!found) {
                this.errors.add("No method [" + method.name + targetDescriptor + "] in [" + target.name
                    + "] to implement [" + source.name + '#' + method.name + method.desc + ']');
            }
        }
    }

    private boolean hasMethod(String className, String name, String descriptor)
    {
        ClassNode node = this.classes.get(className);
        if (node == null) {
            return false;
        }

        if (node.methods.stream().anyMatch(m -> m.name.equals(name) && m.desc.equals(descriptor))) {
            return true;
        }

        return node.interfaces.stream().anyMatch(i -> hasMethod(i, name, descriptor))
            || node.superName != null && hasMethod(node.superName, name, descriptor)
            || node.interfaces.isEmpty() && OBJECT_METHODS.contains(name + descriptor);
    }

    private boolean hasBridge(String className, String key)
    {
        ClassPlan plan = this.plans.get(className);
        if (plan != null && plan.bridges.containsKey(key)) {
            return true;
        }

        ClassNode node = this.classes.get(className);

        return node != null && node.interfaces.stream().anyMatch(i -> hasBridge(i, key));
    }

    /**
     * @return the node of a target or source class (or null if it's outside of the modified JARs)
     */
    private ClassNode getNode(String name)
    {
        ClassNode node = this.classes.get(name);

        return node != null ? node : this.sourceClasses.get(name);
    }

    /**
     * @return the direct super types of the class, as they will be after the modification
     */
    private List<String> getParents(ClassNode node, boolean includeSuperClass)
    {
        List<String> parents = new ArrayList<>(node.interfaces);
        ClassPlan plan = this.plans.get(node.name);
        if (plan != null && plan.addedInterface != null) {
            parents.add(plan.addedInterface);
        }
        if (includeSuperClass) {
            String superName = plan != null && plan.superName != null ? plan.superName : node.superName;
            if (superName != null) {
                parents.add(superName);
            }
        }

        return parents;
    }

    private Set<String> getSuperTypes(String name)
    {
        Set<String> result = this.superTypes.get(name);
        if (result == null) {
            result = new HashSet<>();
            ClassNode node = getNode(name);
            if (node != null) {
                for (String parent : getParents(node, true)) {
                    result.add(parent);
                    result.addAll(getSuperTypes(parent));
                }
            }
            this.superTypes.put(name, result);
        }

        return result;
    }

    private Inherited getInherited(String name)
    {
        Inherited result = this.inherited.get(name);
        if (result != null) {
            return result;
        }

        result = new Inherited();
        ClassNode node = getNode(name);
        if (node != null) {
            boolean isInterface = (node.access & Opcodes.ACC_INTERFACE) != 0;

            List<String> parents = getParents(node, !isInterface);
            if (!isInterface && !parents.isEmpty()) {
                result.concrete.addAll(getInherited(parents.get(parents.size() - 1)).concrete);
            }

            // Collect the maximally specific interfaces providing each default bridge method
            for (String parent : parents) {
                for (Map.Entry<String, Set<String>> entry : getInherited(parent).defaults.entrySet()) {
                    result.defaults.computeIfAbsent(entry.getKey(), k -> new LinkedHashSet<>())
                        .addAll(entry.getValue());
                }
            }
            for (Set<String> providers : result.defaults.values()) {
                providers
                    .removeIf(p -> providers.stream().anyMatch(o -> !o.equals(p) && getSuperTypes(o).contains(p)));
            }

            if (this.sourceClasses.containsKey(name)) {
                addSourceDefaults(node, result);
            } else {
                addTargetBridges(node, isInterface, result);
            }
            result.defaults.keySet().removeAll(result.concrete);
        }

        this.inherited.put(name, result);

        return result;
    }

    /**
     * The source interfaces can contain default methods too (like the bridges generated by the Java compiler for
     * covariant return types).
     */
    private void addSourceDefaults(ClassNode node, Inherited result)
    {
        for (MethodNode method : node.methods) {
            if ((method.access & (Opcodes.ACC_ABSTRACT | Opcodes.ACC_STATIC | Opcodes.ACC_PRIVATE)) == 0
                && method.desc.contains('L' + this.sourcePrefix)) {
                String key = method.name + method.desc;
                if ((node.access & Opcodes.ACC_INTERFACE) != 0) {
                    result.defaults.put(key, new LinkedHashSet<>(Set.of(node.name)));
                } else {
                    result.concrete.add(key);
                }
            }
        }
    }

    private void addTargetBridges(ClassNode node, boolean isInterface, Inherited result)
    {
        Map<String, Bridge> declared = this.plans.containsKey(node.name) ? this.plans.get(node.name).bridges : Map.of();

        // Inheriting several default bridge methods from unrelated interfaces is ambiguous for the JVM
        for (Map.Entry<String, Set<String>> entry : result.defaults.entrySet()) {
            String key = entry.getKey();
            if (entry.getValue().size() > 1 && !declared.containsKey(key) && !result.concrete.contains(key)) {
                int index = key.indexOf('(');
                String descriptor = key.substring(index);
                Bridge bridge =
                    new Bridge(key.substring(0, index), descriptor, toTargetDescriptor(descriptor), false);
                if (!hasMethod(node.name, bridge.name(), bridge.targetDescriptor())) {
                    this.errors.add("No method [" + bridge.name() + bridge.targetDescriptor() + "] in [" + node.name
                        + "] to resolve the conflict between the bridge methods of " + entry.getValue());
                }
                plan(node.name).bridges.put(key, bridge);
                declared = this.plans.get(node.name).bridges;
                if (isInterface) {
                    redeclare(node, bridge);
                }
            }
        }

        for (Bridge bridge : declared.values()) {
            if (!bridge.isStatic()) {
                if (isInterface) {
                    result.defaults.put(bridge.key(), new LinkedHashSet<>(Set.of(node.name)));
                } else {
                    result.concrete.add(bridge.key());
                }
            }
        }
    }

    /**
     * The Java compiler always generates a bridge method next to the method it bridges, and the libraries generating
     * implementations (like Mockito) rely on it: they otherwise consider the inherited method as being bridged by the
     * bridge method and don't implement it. So the bridged method is redeclared next to a bridge method generated in
     * a sub interface, which is only possible if all the inherited declarations are abstract.
     */
    private void redeclare(ClassNode node, Bridge bridge)
    {
        if (node.methods.stream()
            .anyMatch(m -> m.name.equals(bridge.name()) && m.desc.equals(bridge.targetDescriptor()))) {
            // Already declared
            return;
        }

        List<MethodNode> declarations = new ArrayList<>();
        for (String superType : getSuperTypes(node.name)) {
            ClassNode superNode = this.classes.get(superType);
            if (superNode != null) {
                superNode.methods.stream()
                    .filter(m -> m.name.equals(bridge.name()) && m.desc.equals(bridge.targetDescriptor())
                        && (m.access & Opcodes.ACC_STATIC) == 0)
                    .forEach(declarations::add);
            }
        }

        if (declarations.stream().allMatch(m -> (m.access & Opcodes.ACC_ABSTRACT) != 0)) {
            MethodNode declaration = declarations.get(0);
            this.plans.get(node.name).redeclared.add(new MethodNode(Opcodes.ACC_PUBLIC | Opcodes.ACC_ABSTRACT,
                declaration.name, declaration.desc, declaration.signature,
                declaration.exceptions.toArray(new String[0])));
        }
    }

    /**
     * @param name the internal name of a class
     * @return true if the class needs to be modified
     */
    boolean accept(String name)
    {
        return this.plans.containsKey(name);
    }

    /**
     * @param bytes the class to modify
     * @return the modified class
     */
    byte[] bridge(byte[] bytes)
    {
        ClassNode target = new ClassNode();
        new ClassReader(bytes).accept(target, 0);
        ClassPlan plan = this.plans.get(target.name);

        if (plan.addedInterface != null) {
            hideFromCompiler(target);
            target.interfaces.add(plan.addedInterface);
        }

        if (plan.superName != null) {
            changeSuperClass(target, plan.superName);
        }

        boolean isInterface = (target.access & Opcodes.ACC_INTERFACE) != 0;
        for (Bridge bridge : plan.bridges.values()) {
            target.methods.add(createBridge(target.name, isInterface, bridge));
            ++this.bridgeCount;
        }
        target.methods.addAll(plan.redeclared);

        ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_MAXS);
        target.accept(writer);

        return writer.toByteArray();
    }

    private void changeSuperClass(ClassNode target, String superName)
    {
        String previousSuperName = target.superName;
        ClassNode source = this.sourceClasses.get(superName);

        hideFromCompiler(target);
        target.superName = superName;

        // Call the constructors of the new super class
        for (MethodNode method : target.methods) {
            if (method.name.equals(CONSTRUCTOR)) {
                for (AbstractInsnNode instruction : method.instructions) {
                    if (instruction instanceof MethodInsnNode call && call.getOpcode() == Opcodes.INVOKESPECIAL
                        && call.owner.equals(previousSuperName) && call.name.equals(CONSTRUCTOR)) {
                        if (source.methods.stream()
                            .noneMatch(m -> m.name.equals(CONSTRUCTOR) && m.desc.equals(call.desc))) {
                            this.errors.add(
                                "No constructor [" + call.desc + "] in [" + superName + "] for [" + target.name + ']');
                        }
                        call.owner = superName;
                    }
                }
            }
        }
    }

    /**
     * Make sure the class has a generic signature since it's what the Java compiler uses to resolve the super types.
     */
    private static void hideFromCompiler(ClassNode target)
    {
        if (target.signature == null) {
            StringBuilder builder = new StringBuilder();
            builder.append('L').append(target.superName).append(';');
            for (String interfaceName : target.interfaces) {
                builder.append('L').append(interfaceName).append(';');
            }
            target.signature = builder.toString();
        }
    }

    private MethodNode createBridge(String owner, boolean isInterface, Bridge bridge)
    {
        // The bridge flag is needed for the libraries generating implementations (like Mockito) to understand that
        // it's an alternative of the method with the same name and parameters
        int access = Opcodes.ACC_PUBLIC | Opcodes.ACC_SYNTHETIC | Opcodes.ACC_BRIDGE;
        if (bridge.isStatic()) {
            access |= Opcodes.ACC_STATIC;
        }
        MethodNode method = new MethodNode(access, bridge.name(), bridge.sourceDescriptor(), null, null);

        method.visitCode();
        int slot = 0;
        if (!bridge.isStatic()) {
            method.visitVarInsn(Opcodes.ALOAD, slot++);
        }
        for (Type argument : Type.getArgumentTypes(bridge.sourceDescriptor())) {
            method.visitVarInsn(argument.getOpcode(Opcodes.ILOAD), slot);
            convert(method, argument, true);
            slot += argument.getSize();
        }

        int opcode;
        if (bridge.isStatic()) {
            opcode = Opcodes.INVOKESTATIC;
        } else {
            opcode = isInterface ? Opcodes.INVOKEINTERFACE : Opcodes.INVOKEVIRTUAL;
        }
        method.visitMethodInsn(opcode, owner, bridge.name(), bridge.targetDescriptor(), isInterface);

        convert(method, Type.getReturnType(bridge.targetDescriptor()), false);
        method.visitInsn(Type.getReturnType(bridge.sourceDescriptor()).getOpcode(Opcodes.IRETURN));
        method.visitMaxs(0, 0);
        method.visitEnd();

        return method;
    }

    /**
     * Convert the value on top of the stack.
     *
     * @param method the method to add the instructions to
     * @param type the type of the value on top of the stack
     * @param toTarget true to convert from the source type to the target type, false for the other way
     */
    private void convert(MethodNode method, Type type, boolean toTarget)
    {
        String fromPrefix = toTarget ? this.sourcePrefix : this.targetPrefix;

        if (type.getSort() == Type.ARRAY) {
            Type element = type.getElementType();
            if (element.getSort() == Type.OBJECT && element.getInternalName().startsWith(fromPrefix)) {
                String converted = convert(element.getInternalName(), toTarget);
                method.visitLdcInsn(Type.getObjectType(converted));
                method.visitMethodInsn(Opcodes.INVOKESTATIC, UTILS, "toArray",
                    "([Ljava/lang/Object;Ljava/lang/Class;)[Ljava/lang/Object;", false);
                method.visitTypeInsn(Opcodes.CHECKCAST, "[L" + converted + ';');
            }
        } else if (type.getSort() == Type.OBJECT && type.getInternalName().startsWith(fromPrefix)) {
            String converted = convert(type.getInternalName(), toTarget);
            if (this.twinEnums.contains(toTarget ? converted : type.getInternalName())) {
                method.visitLdcInsn(Type.getObjectType(converted));
                method.visitMethodInsn(Opcodes.INVOKESTATIC, UTILS, "toEnum",
                    "(Ljava/lang/Object;Ljava/lang/Class;)Ljava/lang/Object;", false);
            }
            method.visitTypeInsn(Opcodes.CHECKCAST, converted);
        }
    }

    private String convert(String internalName, boolean toTarget)
    {
        return toTarget ? this.targetPrefix + internalName.substring(this.sourcePrefix.length())
            : toSource(internalName);
    }

    private String toSource(String internalName)
    {
        return this.sourcePrefix + internalName.substring(this.targetPrefix.length());
    }

    private String toSourceDescriptor(String descriptor)
    {
        return descriptor.replace('L' + this.targetPrefix, 'L' + this.sourcePrefix);
    }

    private String toTargetDescriptor(String descriptor)
    {
        return descriptor.replace('L' + this.sourcePrefix, 'L' + this.targetPrefix);
    }

    /**
     * @return the number of generated bridge methods
     */
    int getBridgeCount()
    {
        return this.bridgeCount;
    }

    /**
     * @return the problems found while bridging
     */
    List<String> getErrors()
    {
        return this.errors;
    }
}
